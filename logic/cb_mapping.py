def get_map_info(mapping_mode):
    """返回 (rows, cols, map_list)"""
    if mapping_mode not in MAPPING_TABLES:
        raise ValueError(f"不支持的映射模式: {mapping_mode}")
    val = MAPPING_TABLES[mapping_mode]
    # 三元组格式
    if isinstance(val, (tuple, list)) and len(val) == 3 and isinstance(val[2], list):
        rows, cols, data = val
        if rows * cols != len(data):
            raise ValueError(f"映射模式 {mapping_mode} 行列乘积与数据长度不匹配")
        return rows, cols, data
    # 纯列表格式（默认32×18）
    if isinstance(val, list) and len(val) == 576:
        return 32, 18, val
    # 其他情况尝试直接作为列表，根据长度推断
    if isinstance(val, list):
        total = len(val)
        # 假设宽为18，高为 total//18
        if total % 18 == 0:
            return total // 18, 18, val
        # 否则假设32行
        if total % 32 == 0:
            return 32, total // 32, val
        raise ValueError(f"无法从长度 {total} 推断映射表行列，请使用 (rows, cols, list) 格式")
    raise ValueError(f"映射模式 {mapping_mode} 数据格式错误")

def apply_mapping(input_data, mapping_mode):
    """将输入数据按映射表进行行重排，返回重排后的列表"""
    rows, cols, map_table = get_map_info(mapping_mode)
    if len(input_data) != rows * cols:
        raise ValueError(f"输入数据长度 {len(input_data)} 与映射模式所需 {rows}x{cols} 不匹配")
    if len(map_table) != rows * cols:
        raise ValueError(f"映射表数据长度错误")

    input_matrix = [input_data[r*cols:(r+1)*cols] for r in range(rows)]
    map_matrix   = [map_table[r*cols:(r+1)*cols] for r in range(rows)]

    result_matrix = []
    for r in range(rows):
        out_row = []
        for c in range(cols):
            src_row = map_matrix[r][c]
            if not (0 <= src_row < rows):
                raise ValueError(f"映射表索引越界: mode {mapping_mode}, 位置 ({r},{c}) = {src_row}")
            out_row.append(input_matrix[src_row][c])
        result_matrix.append(out_row)

    return [val for row in result_matrix for val in row]

def generate_672_from_mapped(mapped_data, nd_value, output_path, log_func=print):
    """仅支持 32×18 数据打包为 672 格式"""
    if len(mapped_data) != 576:
        raise ValueError("当前仅支持 32×18 (576) 的数据")
    rows, cols = 32, 18
    matrix = [mapped_data[r*cols:(r+1)*cols] for r in range(rows)]

    def full_col(c):   return [matrix[r][c] for r in range(rows)]
    def upper_col(c):  return [matrix[r][c] for r in range(0, 16)]
    def lower_col(c):  return [matrix[r][c] for r in range(16, 32)]

    right_seq = [
        (17, 16, True), (16, 15, False), (14, 13, True),
        (13, 12, False), (11, 10, True), (10, 9, False)
    ]
    left_seq = [
        (0, 1, True), (1, 2, False), (3, 4, True),
        (4, 5, False), (6, 7, True), (7, 8, False)
    ]

    result = [str(nd_value)] * 48
    for col_f, col_h, first_full in right_seq:
        if first_full:
            part = full_col(col_f) + upper_col(col_h)
        else:
            part = lower_col(col_f) + full_col(col_h)
        result.extend(str(v) for v in part)

    result.extend([str(nd_value)] * 48)
    for col_f, col_h, first_full in left_seq:
        if first_full:
            part = full_col(col_f) + upper_col(col_h)
        else:
            part = lower_col(col_f) + full_col(col_h)
        result.extend(str(v) for v in part)

    if len(result) != 672:
        raise ValueError("内部错误：生成数据长度不为672")
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(','.join(result))
    log_func(f"672数据已保存至: {output_path}")